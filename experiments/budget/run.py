def summary_json(result: Dict[str, Any], seeds: Sequence[int], runs: Sequence[int], n_tasks: int,
                 commit: str, pilot: bool = False) -> str:
    doc = {
        "experiment": "verification budget (PREREG_BUDGET experiment 3)",
        "prereg_path": PREREG_PATH,
        "prereg_merge_commit": PREREG_MERGE_COMMIT,
        "prereg_file_commit": PREREG_FILE_COMMIT,
        "runner_base_commit": commit,
        "model": MODEL_NAME,
        "pilot": pilot,
        "seeds": list(seeds),
        "runs": [runs[0], runs[-1]],
        "tasks": n_tasks,
        "margins": {"delta_tok": DELTA_TOK, "delta_sr": DELTA_SR, "c_harm": C_HARM},
        "half_width_flag": TOK_HALF_WIDTH_FLAG,
        "sr_half_width_plan": SR_HALF_WIDTH_PLAN,
        "amendments": "none",
        "result": _jsonable(result),
    }
    return json.dumps(doc, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()
    except Exception:  # pragma: no cover - no git
        return "unknown"


def _write(path: Path, text: str, written: Dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    written[str(path)] = text


def resolve_args(args: argparse.Namespace) -> Tuple[List[int], List[int], int]:
    """The (seeds, runs, tasks) triple the flags select; ``--pilot`` ignores them (§13)."""
    if args.pilot:
        return [PILOT_SEED], list(PILOT_RUNS), PILOT_TASKS
    return list(args.seeds), list(range(args.run_start, args.run_start + args.runs)), args.tasks


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", type=int, nargs="+", default=list(SEEDS))
    ap.add_argument("--runs", type=int, default=RUNS, help="runs per seed (registered: 40)")
    ap.add_argument("--run-start", type=int, default=0, help="first run index (registered: 0)")
    ap.add_argument("--tasks", type=int, default=TASKS, help="tasks per run (registered: 100)")
    ap.add_argument("--pilot", action="store_true",
                    help=f"the §13 step 3 pilot: seed {PILOT_SEED}, run indices "
                         f"{PILOT_RUNS[0]}-{PILOT_RUNS[1]}, {PILOT_TASKS} tasks")
    ap.add_argument("--jobs", type=int, default=1, help="worker processes (output does not depend on it)")
    ap.add_argument("--results", type=Path, nargs="?", const=DEFAULT_RESULTS, default=None,
                    help=f"write the Markdown report (bare flag: {DEFAULT_RESULTS.relative_to(REPO_ROOT)})")
    ap.add_argument("--summary-dir", type=Path, nargs="?", const=DEFAULT_SUMMARY_DIR, default=None,
                    help="write summary.json and runs.jsonl (bare flag: "
                         f"{DEFAULT_SUMMARY_DIR.relative_to(REPO_ROOT)})")
    ap.add_argument("--commit", default=None, help="commit id to print in the report (default: git HEAD)")
    return ap


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    seeds, runs, n_tasks = resolve_args(args)
    raw = run_all(seeds, runs, n_tasks, args.jobs)
    result = analyse(raw)
    commit = args.commit or git_commit()
    report = results_markdown(result, seeds, runs, n_tasks, commit, pilot=args.pilot)
    written: Dict[str, str] = {}
    if args.results is not None:
        _write(args.results, report, written)
    if args.summary_dir is not None:
        _write(args.summary_dir / "summary.json",
               summary_json(result, seeds, runs, n_tasks, commit, args.pilot), written)
        _write(args.summary_dir / "runs.jsonl",
               "".join(json.dumps(r, sort_keys=True, separators=(",", ":")) + "\n"
                       for r in run_rows(raw)), written)
    sys.stdout.write(report)
    for path in written:
        print(f"wrote {path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())




