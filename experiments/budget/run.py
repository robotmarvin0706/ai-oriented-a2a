def _f(x: Any, signed: bool = False, nd: int = 3) -> str:
    if x is None:
        return "n/a"
    v = float(x) + 0.0
    return f"{v:+.{nd}f}" if signed else f"{v:.{nd}f}"


def _ci(c: Dict[str, Any]) -> str:
    return f"{_f(c['estimate'], True)} [{_f(c['lo'], True)}, {_f(c['hi'], True)}]"


def _int(x: Any) -> str:
    return "n/a" if x is None else f"{float(x):,.0f}"


def _pct(x: Any) -> str:
    return "n/a" if x is None else f"{100 * float(x):.1f}%"


def _share(part: Any, whole: Any) -> str:
    if not whole or whole <= 0:
        return "n/a"
    return _pct(float(part) / float(whole))


def _rule_label(rule: Optional[str], label: Optional[str]) -> str:
    if rule is None or label is None:
        return "n/a"
    return f"{rule}: `{label}`"


