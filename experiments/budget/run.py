def _run_one(args: Tuple[int, int, int]) -> Dict[str, Any]:
    seed, run, n_tasks = args
    return {"seed": seed, "run": run, "arms": run_endpoints(seed, run, n_tasks=n_tasks)}


def run_all(seeds: Sequence[int], runs: Sequence[int], n_tasks: int,
            jobs: int = 1) -> List[Dict[str, Any]]:
    """Simulate every (seed, run); order and content do not depend on ``jobs``."""
    work = [(s, r, n_tasks) for s in seeds for r in runs]
    if jobs <= 1:
        return [_run_one(w) for w in work]
    with Pool(jobs) as pool:
        return list(pool.imap(_run_one, work, chunksize=1))


def _jsonable(obj: Any) -> Any:
    """Fraction to float, otherwise leave the JSON-ready value alone."""
    if isinstance(obj, Fraction):
        return float(obj)
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    return obj


def run_rows(runs: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Compact per-run rows for ``runs.jsonl``: one row per (seed, run)."""
    rows = []
    for r in runs:
        control = r["arms"].get("C", {})
        rows.append({
            "seed": r["seed"],
            "run": r["run"],
            "k_e": control.get("k_e"),
            "k_s": control.get("k_s"),
            "arms": {label: _jsonable(r["arms"][label]) for label in ARM_ORDER if label in r["arms"]},
        })
    return rows


